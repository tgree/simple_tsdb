#ifndef __SRC_LIBTSDB_ACL_H
#define __SRC_LIBTSDB_ACL_H

#include <exception>
#include <string>
#include <vector>
#include <stdint.h>

namespace tsdb
{
    // Permissions a user can hold on a database.
    enum permission : uint32_t
    {
        PERM_READ   = (1 << 0),
        PERM_WRITE  = (1 << 1),
        PERM_DELETE = (1 << 2),
        PERM_ALL    = (PERM_READ | PERM_WRITE | PERM_DELETE),
    };

    // Parses a comma-separated list of permission names, such as
    // "read,write" or "all", ignoring case.  Returns 0 if the list is empty
    // or any entry isn't a permission name.
    uint32_t parse_permissions(const std::string& s);

    // Formats a permission mask as a comma-separated list, such as
    // "read,write", or "all" when every permission is set.
    std::string permissions_to_string(uint32_t perms);

    // One line of the acl file: the permissions user holds on database,
    // which is "*" for every database.
    struct acl_entry
    {
        std::string user;
        std::string database;
        uint32_t    perms;
    };

    // Thrown by root::grant() and root::revoke() when the root has no acl
    // file.  This only happens in tsdbcli2, so it has no status code.
    struct acls_disabled_exception : public std::exception
    {
        virtual const char* what() const noexcept override
        {
            return "Access control is off; use ENABLE ACLS to turn it on.";
        }
    };

    // The first line of every acl file that tsdbcli2 writes.
    inline constexpr const char acl_file_header[] =
        "# Generated by tsdbcli2; edit only with tsdbcli2's GRANT and REVOKE "
        "commands.";

    // An access control list, as stored in a root's acl file.  Each line
    // is "<user> <database> <permissions>"; blank lines and lines starting
    // with '#' are ignored.
    struct acl
    {
        // Sorted by user and then database, with at most one entry for each
        // pair.
        std::vector<acl_entry> entries;

        // Returns the permissions user holds on database: those granted on
        // that database plus those granted on "*".
        uint32_t permissions(const std::string& user,
                             const std::string& database) const;

        // Adds perms to user's entry for database, creating the entry if
        // there isn't one.
        void grant(const std::string& user, const std::string& database,
                   uint32_t perms);

        // Removes perms from user's entry for database, deleting the entry if
        // no permissions remain.  Does nothing if there is no such entry.
        // Revoking on "*" only changes the "*" entry.
        void revoke(const std::string& user, const std::string& database,
                    uint32_t perms);

        // Returns the text of the acl file, starting with acl_file_header.
        std::string to_string() const;

        // Parses the text of an acl file, throwing
        // invalid_acl_file_exception with the line number of the first line
        // that isn't valid.
        static acl parse(const std::string& text);
    };
}

#endif /* __SRC_LIBTSDB_ACL_H */
